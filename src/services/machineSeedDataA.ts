import type { Machine, MachineDayStats } from "../types/machine";

export const isoDay = (offset = 0) => {
  const d = new Date();
  d.setDate(d.getDate() + offset);
  return d.toISOString().slice(0, 10);
};

export const make7DayStats = (avgRun: number, avgIdle: number, avgDown: number): MachineDayStats[] => {
  return Array.from({ length: 7 }, (_, i) => {
    const date = isoDay(-(6 - i));
    const noise = (i % 3) * 0.4 - 0.2;
    return {
      date,
      runHours: Math.max(0, Math.round((avgRun + noise) * 10) / 10),
      idleHours: Math.max(0, Math.round((avgIdle - noise * 0.5) * 10) / 10),
      downtimeHours: Math.max(0, Math.round((avgDown + (i === 5 ? 1.5 : 0)) * 10) / 10),
    };
  });
};

